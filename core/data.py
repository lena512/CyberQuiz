def get_public_questions():
    """Возвращает вопросы без правильных ответов и пояснений."""
    return [
        {
            "id": question["id"],
            "text": question["text"],
            "options": question["options"],
        }
        for question in QUESTIONS
    ]


def calculate_result(answers):
    """Проверяет ответы и формирует итоговый результат."""
    correct_count = sum(
        1
        for question in QUESTIONS
        if answers.get(str(question["id"])) == question["correct"]
    )

    total_questions = len(QUESTIONS)
    percentage = round(correct_count / total_questions * 100)

    if correct_count == 5:
        grade = "Отлично"
    elif correct_count == 4:
        grade = "Хорошо"
    elif correct_count == 3:
        grade = "Удовлетворительно"
    else:
        grade = "Неудовлетворительно"

    return {
        "correct_count": correct_count,
        "total_questions": total_questions,
        "percentage": percentage,
        "grade": grade,
        "passed": correct_count >= 3,
    }